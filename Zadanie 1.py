liczba = int(input("Wybierz liczbę a: "))
liczba2 = int(input("Wybierz liczbę b: "))
print("Wybierz znak + - * /")
znak = str (input())
if znak == "+":
    print(liczba+liczba2)
elif znak == "-":
    print(liczba-liczba2)
elif znak == "*":
    print(liczba*liczba2)
elif znak == "/":
    print(liczba/liczba2)


